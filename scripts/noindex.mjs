/**
 * Кладе у зібраний сайт файл `_headers`, який забороняє пошуковикам
 * індексувати збірку.
 *
 * Потрібно для стейджингу: Netlify сам ставить noindex на прев'ю пул-реквестів
 * і на СТАРІ збірки гілок, але найсвіжіша збірка гілки `dev` індексується
 * нарівні з продакшном — і Google бачить дві копії сайту.
 *
 * Заголовки в `netlify.toml` не можна прив'язати до контексту деплою,
 * тому файл дописується вже після збірки — лише в тих контекстах,
 * де це потрібно.
 */
import { writeFileSync } from 'node:fs'

const FILE = '.output/public/_headers'

writeFileSync(FILE, '/*\n  X-Robots-Tag: noindex\n')
console.log(`[noindex] ${FILE} — збірку закрито від пошуковиків`)
